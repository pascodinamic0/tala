export function getListing(id: string): Listing | undefined {
  return LISTINGS.find((l) => l.id === id);
}

export function listingsByCategory(slug: string): Listing[] {
  return LISTINGS.filter((l) => l.category === slug);
}

export function featuredListings(): Listing[] {
  return LISTINGS.filter((l) => l.featured);
}

export function searchListings(q: string): Listing[] {
  const needle = q.trim().toLowerCase();
  if (!needle) return LISTINGS;
  return LISTINGS.filter(
    (l) =>
      l.title.toLowerCase().includes(needle) ||
      l.description.toLowerCase().includes(needle) ||
      l.commune.toLowerCase().includes(needle) ||
      l.brand?.toLowerCase().includes(needle) ||
      l.tags?.some((t) => t.toLowerCase().includes(needle)),
  );
}
